#!/usr/bin/env python3
"""Generate the checked-in 25-edge x 16-sample SVG waveform ROM."""
from __future__ import annotations

import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "fpga_hub/iq_bridge/svg_modem/rtl/svg_waveform.hex"
SCALE = 8192
SAMPLES_PER_EDGE = 16


def _round_away(value: float) -> int:
    """Round to nearest integer, with exact half values away from zero."""
    if value >= 0:
        return math.floor(value + 0.5)
    return math.ceil(value - 0.5)


def vertices() -> list[tuple[int, int]]:
    points = []
    for node in range(5):
        angle = math.pi / 2 - node * 2 * math.pi / 5
        points.append((_round_away(SCALE * math.cos(angle)),
                       _round_away(SCALE * math.sin(angle))))
    # The mathematical p0 I value is zero; avoid retaining libm's tiny residue.
    points[0] = (0, SCALE)
    return points


def entries() -> list[int]:
    points = vertices()
    rom: list[int] = []
    for source in range(5):
        for destination in range(5):
            start_i, start_q = points[source]
            end_i, end_q = points[destination]
            delta = (destination - source) % 5
            for k in range(1, SAMPLES_PER_EDGE + 1):
                fraction = k / SAMPLES_PER_EDGE
                line_i = _round_away(start_i + (end_i - start_i) * fraction)
                line_q = _round_away(start_q + (end_q - start_q) * fraction)
                if k == SAMPLES_PER_EDGE:
                    line_i, line_q = end_i, end_q

                if delta == 1:
                    sweep = -2 * math.pi / 5
                    angle = math.pi / 2 - source * 2 * math.pi / 5 + sweep * fraction
                    arc_i = _round_away(SCALE * math.cos(angle))
                    arc_q = _round_away(SCALE * math.sin(angle))
                elif delta == 4:
                    sweep = 2 * math.pi / 5
                    angle = math.pi / 2 - source * 2 * math.pi / 5 + sweep * fraction
                    arc_i = _round_away(SCALE * math.cos(angle))
                    arc_q = _round_away(SCALE * math.sin(angle))
                else:
                    # The star's nonadjacent transitions remain straight even
                    # when arc_mode is selected.
                    arc_i, arc_q = line_i, line_q

                if k == SAMPLES_PER_EDGE:
                    arc_i, arc_q = end_i, end_q

                # 64-bit word layout: arc_q, arc_i, line_q, line_i (MSB first).
                word = ((arc_q & 0xFFFF) << 48) | ((arc_i & 0xFFFF) << 32) | \
                       ((line_q & 0xFFFF) << 16) | (line_i & 0xFFFF)
                rom.append(word)

    if len(rom) != 25 * SAMPLES_PER_EDGE:
        raise AssertionError(f"expected 400 entries, generated {len(rom)}")
    for edge in range(25):
        destination = edge % 5
        final = rom[edge * SAMPLES_PER_EDGE + SAMPLES_PER_EDGE - 1]
        i_value, q_value = points[destination]
        if (final & 0xFFFF) != (i_value & 0xFFFF):
            raise AssertionError("linear final sample missed destination I")
        if ((final >> 16) & 0xFFFF) != (q_value & 0xFFFF):
            raise AssertionError("linear final sample missed destination Q")
        if ((final >> 32) & 0xFFFF) != (i_value & 0xFFFF):
            raise AssertionError("arc final sample missed destination I")
        if ((final >> 48) & 0xFFFF) != (q_value & 0xFFFF):
            raise AssertionError("arc final sample missed destination Q")
    return rom


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    rom = entries()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="ascii", newline="\n") as output:
        output.write("// Generated by scripts/make_svg_waveform_rom.py; do not edit by hand.\n")
        output.write("// 400 x 64-bit words: {arc_q, arc_i, line_q, line_i}; edge index source*5+destination, k=1..16.\n")
        for word in rom:
            output.write(f"{word:016x}\n")
    print(f"Wrote {len(rom)} waveform entries to {args.output}")


if __name__ == "__main__":
    main()
